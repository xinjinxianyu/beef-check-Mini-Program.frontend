const dishes = rawDishes.map(([category, name, tip, steps], index) => {
  const aliases = name === '菲力牛排'
    ? ['里脊牛排']
    : name === '西冷牛排'
      ? ['外脊牛排']
      : name === '肉眼牛排'
        ? ['眼肉牛排', '肋眼牛排']
        : name === 'T骨牛排'
          ? ['T-bone牛排']
          : name === '牛腩面'
            ? ['港式牛腩面']
            : name === '家常牛肉汤'
              ? ['白萝卜牛肉汤']
              : []
  return {
    id: `beef_dish_${index + 1}`,
    category,
    name,
    aliases,
    tip,
    steps: steps || null
  }
})

function findBeefDish(question) {
  const normalized = String(question || '').replace(/\s+/g, '').toLowerCase()
  if (!normalized) return null
  const matches = dishes
    .filter((dish) => [dish.name].concat(dish.aliases).some((name) => normalized.includes(name.toLowerCase())))
    .sort((left, right) => right.name.length - left.name.length)
  return matches[0] || null
}

function buildDishRecipeAnswer(dish, context) {
  if (!dish) return ''
  const guide = categoryGuides[dish.category]
  const cutName = context && context.cutName ? context.cutName : '牛肉'
  const hasRecognizedCut =
    context && context.source === 'local-recognition' && context.cutId && context.cutId !== 'generic'
  const hasQuestionCut = context && context.source === 'question-text' && context.cutId !== 'generic'
  const subject = hasRecognizedCut
    ? `当前识别为${cutName}，`
    : hasQuestionCut
      ? `结合${cutName}的特点，`
      : ''
  const steps = (dish.steps || guide.steps).map((step, index) => `${index + 1}. ${step}`).join('\n')

  return `${subject}可以按${guide.label}的思路制作${dish.name}。\n\n${steps}\n\n这道菜的重点：${dish.tip}\n\n调味时先少量多次加入盐和酱油，牛肉片熟透后再食用。`
}

function findTechniqueGuide(question) {
  const normalized = String(question || '')
  if (/牛排|煎|烤/.test(normalized)) return categoryGuides.steak
  if (/火锅|锅类|锅底|涮/.test(normalized)) return categoryGuides.hotpot
  if (/牛杂|牛肚|牛筋|牛舌|内脏/.test(normalized)) return categoryGuides.offal
  if (/蒸/.test(normalized)) return categoryGuides.steam
  if (/汤|羹/.test(normalized)) return categoryGuides.soup
  if (/面|饺|馄饨|锅贴|馅饼|烧卖/.test(normalized)) return categoryGuides.staple
  if (/卤|酱|拌|凉菜|肉干|风干/.test(normalized)) return categoryGuides.deli
  if (/炖|焖|烧|煨|煲|烩/.test(normalized)) return categoryGuides.stew
  if (/溜|熘|炒|爆|滑/.test(normalized)) return categoryGuides.stir
  return null
}

function buildTechniqueRecipeAnswer(question, context) {
  const guide = findTechniqueGuide(question)
  if (!guide) return ''
  const cutName = context && context.cutName ? context.cutName : '牛肉'
  const hasRecognizedCut =
    context && context.source === 'local-recognition' && context.cutId && context.cutId !== 'generic'
  const hasQuestionCut = context && context.source === 'question-text' && context.cutId !== 'generic'
  const subject = hasRecognizedCut
    ? `当前识别为${cutName}，`
    : hasQuestionCut
      ? `结合${cutName}的特点，`
      : ''
  const steps = guide.steps.map((step, index) => `${index + 1}. ${step}`).join('\n')
  return `${subject}可以按${guide.label}的思路来做。\n\n${steps}\n\n请结合菜品口味调整配料；牛肉片或肉块完全熟透后再食用。`
}

